/// New operation kinds for video generation
#[derive(Debug, Clone)]
pub enum VideoOp {
    // 3D convolution (spatial + temporal)
    Conv3d {
        in_ch: u32,
        out_ch: u32,
        kernel: (u32, u32, u32), // (temporal, height, width)
        stride: (u32, u32, u32),
        padding: (u32, u32, u32),
    },

    // Temporal attention (across frames at same spatial position)
    TemporalAttention {
        dim: u32,
        heads: u32,
        causal: bool,
    },

    // Joint spatial-temporal attention (full 3D self-attention)
    SpatialTemporalAttention {
        dim: u32,
        heads: u32,
    },

    // Frame interpolation
    FrameInterpolation {
        scale: u32,
    },

    // 3D VAE decode (video latent → video frames)
    VideoVaeDecode {
        latent_channels: u32,
        num_frames: u32,
    },

    // Frame-wise schedule for long video generation
    FrameSchedule {
        keyframe_interval: u32,   // generate keyframe every N frames
        interpolation_steps: u32, // interpolate between keyframes
    },
}

#[derive(Debug, Clone)]
pub struct VideoPipeline {
    /// Total frames to generate
    pub num_frames: u32,
    /// Frames processed per denoising step (sliding window)
    pub window_size: u32, // typically 4-8 frames
    /// Overlap between windows (for temporal consistency)
    pub overlap: u32, // typically 1-2 frames
    /// Generated keyframes (every keyframe_interval frames)
    pub keyframes: Vec<FrameIndex>,
    /// Interpolation between keyframes
    pub interpolate: bool,
}

/// A gap between two keyframes that must be filled via interpolation.
#[derive(Debug, Clone)]
pub struct InterpolationGap {
    /// Index of the keyframe that starts this gap.
    pub start_frame: u32,
    /// Index of the keyframe that ends this gap.
    pub end_frame: u32,
    /// How many interpolated frames to insert between start and end.
    pub num_interpolations: u32,
}

/// Describes a complete frame schedule for video generation:
/// which frames are keyframes (generated by the image provider)
/// and which gaps are filled by interpolation.
#[derive(Debug, Clone)]
pub struct FrameSchedule {
    /// The list of keyframe indices in temporal order.
    pub keyframes: Vec<FrameIndex>,
    /// Gaps between consecutive keyframes that need interpolation.
    pub interpolation_gaps: Vec<InterpolationGap>,
    /// Keyframe interval used to derive the schedule.
    pub keyframe_interval: u32,
    /// Interpolation steps between keyframes.
    pub interpolation_steps: u32,
}

impl FrameSchedule {
    /// Build a frame schedule for `num_frames` frames, placing a keyframe
    /// every `keyframe_interval` frames and setting `interpolation_steps`
    /// as the number of interpolated frames between consecutive keyframes.
    pub fn new(num_frames: u32, _fps: u32, keyframe_interval: u32) -> Self {
        let scheduler = frame_scheduler::FrameScheduler::new(
            num_frames,
            keyframe_interval,
            1, // interpolation_steps handled separately
        );
        let raw_keyframes = scheduler.schedule_keyframes();

        let mut keyframes: Vec<FrameIndex> = raw_keyframes;
        keyframes.sort();
        keyframes.dedup();

        let mut interpolation_gaps = Vec::new();
        // Cap interpolation so we never exceed num_frames
        let safe_interpolation_steps = keyframe_interval.saturating_sub(1).min(4);

        for window in keyframes.windows(2) {
            let start = window[0];
            let end = window[1];
            let range = end - start;
            if range > 1 {
                let steps = safe_interpolation_steps.min(range - 1);
                if steps > 0 {
                    interpolation_gaps.push(InterpolationGap {
                        start_frame: start,
                        end_frame: end,
                        num_interpolations: steps,
                    });
                }
            }
        }

        Self {
            keyframes,
            interpolation_gaps,
            keyframe_interval,
            interpolation_steps: safe_interpolation_steps,
        }
    }
}

